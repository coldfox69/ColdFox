import { describe, expect, it } from 'vitest';
import { buildOutreachCampaign } from '@/lib/agents/outreach';

describe('buildOutreachCampaign', () => {
  it('uses the defaults of a campaign', () => {
    const input = buildOutreachCampaign({
      name: 'Shopify lead generation outreach',
      description: 'Audience generated by the agent.',
      outreach: {},
      leadListId: 'list-1',
    });
    expect(input.name).toBe('Shopify lead generation outreach');
    expect(input.lead_list_id).toBe('list-1');
    expect(input.lead_ids).toEqual([]);
    expect(input.daily_limit).toBe(100);
    expect(input.send_window_start).toBe('09:00');
    expect(input.send_window_end).toBe('17:00');
    expect(input.weekdays).toEqual([1, 2, 3, 4, 5]);
    expect(input.timezone).toBe('UTC');
    expect(input.stop_on_reply).toBe(true);
    expect(input.interval_min_seconds).toBe(30);
    expect(input.interval_max_seconds).toBe(70);
  });

  it('keeps the choices of the user', () => {
    const input = buildOutreachCampaign({
      name: 'Campaign',
      description: 'Description',
      outreach: {
        mailbox_id: 'mailbox-1',
        template_id: 'template-1',
        campaign_name: 'ignored here',
        subject: 'Hello there',
        body: 'Body text',
        timezone: 'Asia/Dhaka',
        daily_limit: 250,
        send_window_start: '08:30',
        send_window_end: '20:00',
        weekdays: [1, 2, 3],
        stop_on_reply: false,
        interval_min_seconds: 45,
        interval_max_seconds: 90,
        ai_personalization: true,
      },
      leadListId: 'list-2',
    });
    expect(input.mailbox_id).toBe('mailbox-1');
    expect(input.template_id).toBe('template-1');
    expect(input.subject).toBe('Hello there');
    expect(input.body).toBe('Body text');
    expect(input.timezone).toBe('Asia/Dhaka');
    expect(input.daily_limit).toBe(250);
    expect(input.send_window_start).toBe('08:30');
    expect(input.weekdays).toEqual([1, 2, 3]);
    expect(input.stop_on_reply).toBe(false);
    expect(input.interval_min_seconds).toBe(45);
    expect(input.ai_personalization).toBe(true);
  });

  it('clamps values that are out of range', () => {
    const input = buildOutreachCampaign({
      name: 'Campaign',
      description: 'Description',
      outreach: { daily_limit: 99999, interval_min_seconds: 0, interval_max_seconds: 100000 },
      leadListId: 'list-3',
    });
    expect(input.daily_limit).toBe(2000);
    expect(input.interval_min_seconds).toBe(1);
    expect(input.interval_max_seconds).toBe(3600);
  });

  it('drops an empty subject or body', () => {
    const input = buildOutreachCampaign({
      name: 'Campaign',
      description: 'Description',
      outreach: { subject: '   ', body: '' },
      leadListId: 'list-4',
    });
    expect(input.subject).toBeUndefined();
    expect(input.body).toBeUndefined();
  });
});
